export function planCatalog(placeSlug: string) {
  const resolved = destinationAliases[placeSlug] || placeSlug;
  const place =
    destinations.find((d) => d.slug === resolved) ||
    destinations.find((d) => d.slug === "san-pedro-de-atacama") ||
    destinations[0];
  const land = place.landscapes?.[0];
  const featured = land ? landscapePlaceSlug[land] : place.slug;
  const stay =
    capsules.find((c) => c.placeSlug === place.slug) ||
    capsules.find((c) => c.placeSlug === featured) ||
    capsules[0];
  const seen = new Set<string>();
  const uniq = (items: CatalogItem[]) =>
    items.filter((i) => {
      if (seen.has(i.slug)) return false;
      seen.add(i.slug);
      return true;
    });
  const food = uniq([
    ...gastronomy.filter((g) => g.placeSlug === place.slug),
    ...gastronomy.filter((g) => land && g.landscapes?.includes(land)),
  ]);
  seen.clear();
  const acts = uniq([
    ...activities.filter((a) => a.placeSlug === place.slug),
    ...activities.filter(
      (a) => land && (a.cluster ?? a.landscapes?.[0]) === land,
    ),
  ]);
  const table =
    food.length > 0
      ? food
      : gastronomy.filter((g) =>
          ["empanadas-de-pino", "sopaipillas", "cazuela"].includes(g.slug),
        );
  return { place, stay, food: table, acts, land };
}

export function mapPoints() {
  return [
    ...destinations.map((d) => ({
      ...d,
      group: "place" as const,
    })),
    ...capsules.map((c) => ({
      ...c,
      group: "capsule" as const,
    })),
  ];
}

export function featuredCapsules() {
  return landscapes
    .map((l) => {
      const item = capsules.find((c) => c.placeSlug === landscapePlaceSlug[l.id]);
      return item ? { item, land: l.id } : null;
    })
    .filter((x): x is { item: CatalogItem; land: Landscape } => Boolean(x));
}

export function destinationsByLandscape(id: Landscape | "all") {
  if (id === "all") return destinations;
  return destinations.filter((d) => d.landscapes?.includes(id));
}
