export function groupedActivities() {
  const groups = landscapes.map((l) => ({
    id: l.id as Landscape | "otros",
    label: l.label,
    sports: ACTIVITY_SPORTS[l.id],
    items: activities.filter((a) => (a.cluster ?? a.landscapes?.[0]) === l.id),
  }));
  const otros = activities.filter((a) => a.cluster === "otros");
  if (otros.length) {
    groups.push({
      id: "otros",
      label: "Otros",
      sports: "Cultura, amaneceres y miradores",
      items: otros,
    });
  }
  return groups;
}

